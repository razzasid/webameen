    'totals',pg_catalog.jsonb_build_object(
      'subtotal_minor',v_version.subtotal_minor::text,
      'taxable_subtotal_minor',v_version.taxable_subtotal_minor::text,
      'cgst_total_minor',v_version.cgst_total_minor::text,
