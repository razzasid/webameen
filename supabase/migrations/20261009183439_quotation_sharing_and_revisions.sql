CREATE FUNCTION private.revoke_quotation_link(
  p_quotation_id uuid,p_link_id uuid
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_user_id uuid := auth.uid(); v_business_id uuid;
  v_quote public.quotations; v_link public.quotation_public_links;
  v_now timestamptz;
BEGIN
  IF v_user_id IS NULL OR p_quotation_id IS NULL OR p_link_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Authenticated owner required';
  END IF;
  SELECT business_id INTO v_business_id FROM public.business_memberships WHERE user_id=v_user_id;
  IF v_business_id IS NULL THEN RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required'; END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/business/'||v_business_id::text,0));
  IF NOT EXISTS (SELECT 1 FROM public.business_memberships
    WHERE business_id=v_business_id AND user_id=v_user_id AND role='owner' AND disabled_at IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required';
  END IF;
  SELECT * INTO v_quote FROM public.quotations
    WHERE business_id=v_business_id AND id=p_quotation_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Quotation unavailable'; END IF;
  SELECT * INTO v_link FROM public.quotation_public_links
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id AND id=p_link_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Quotation link unavailable'; END IF;
  IF v_link.revoked_at IS NULL THEN
    v_now:=pg_catalog.clock_timestamp();
    UPDATE public.quotation_public_links SET
      revoked_by=v_user_id,revoked_at=v_now,revocation_reason='owner_revoked'
      WHERE business_id=v_business_id AND id=p_link_id;
    UPDATE public.quotations SET updated_at=v_now
      WHERE business_id=v_business_id AND id=p_quotation_id;
    v_link.revoked_at:=v_now;
    v_link.revoked_by:=v_user_id;
    v_link.revocation_reason:='owner_revoked';
  END IF;
  RETURN pg_catalog.jsonb_build_object(
    'link_id',v_link.id,'revoked_at',v_link.revoked_at,
    'revocation_reason',v_link.revocation_reason);
END
$fn$;

CREATE FUNCTION private.create_quotation_revision(
  p_quotation_id uuid,p_predecessor_version_id uuid
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_user_id uuid:=auth.uid(); v_business_id uuid;
  v_quote public.quotations; v_predecessor public.quotation_versions;
  v_successor public.quotation_versions; v_new_id uuid:=pg_catalog.gen_random_uuid();
  v_now timestamptz;
BEGIN
  IF v_user_id IS NULL OR p_quotation_id IS NULL OR p_predecessor_version_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Authenticated owner required';
  END IF;
  SELECT business_id INTO v_business_id FROM public.business_memberships WHERE user_id=v_user_id;
  IF v_business_id IS NULL THEN RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required'; END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/business/'||v_business_id::text,0));
  IF NOT EXISTS (SELECT 1 FROM public.business_memberships
    WHERE business_id=v_business_id AND user_id=v_user_id AND role='owner' AND disabled_at IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required';
  END IF;
  SELECT * INTO v_quote FROM public.quotations
    WHERE business_id=v_business_id AND id=p_quotation_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Quotation unavailable'; END IF;

  -- A retry of a revision returns its original successor, even if later
  -- workflow steps have already advanced the quotation.
  SELECT * INTO v_successor FROM public.quotation_versions
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id
      AND previous_version_id=p_predecessor_version_id;
  IF FOUND THEN RETURN v_successor.id; END IF;
  IF EXISTS (SELECT 1 FROM public.invoices
      WHERE business_id=v_business_id AND quotation_id=p_quotation_id) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='An invoiced quotation cannot be revised';
  END IF;
  IF v_quote.current_version_id<>p_predecessor_version_id THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Only the current quotation version can be revised';
  END IF;
  SELECT * INTO v_predecessor FROM public.quotation_versions
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id
      AND id=p_predecessor_version_id FOR UPDATE;
  IF NOT FOUND OR v_predecessor.shared_at IS NULL OR v_predecessor.state='superseded' THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Only a frozen quotation can be revised';
  END IF;
  v_now:=pg_catalog.clock_timestamp();
  INSERT INTO public.quotation_versions(
    id,business_id,quotation_id,version_number,previous_version_id,state,edit_sequence,
    created_by,created_at,edited_at,valid_until,
    seller_display_name,seller_contact_email,seller_contact_phone,seller_postal_address,
    seller_country_code,seller_state_code,seller_gst_registered,seller_gstin,
    seller_logo_asset_key,seller_logo_sha256,seller_signature_asset_key,seller_signature_sha256,
    buyer_display_name,buyer_contact_name,buyer_email,buyer_phone,buyer_billing_address,
    buyer_state_code,buyer_gstin_applicable,buyer_gstin,
    currency_code,currency_exponent,quantity_scale,calculation_rule_code,price_tax_mode,
    gst_auto_treatment,gst_treatment_override,gst_treatment,document_time_zone,
    place_of_supply_applicable,place_of_supply_state_code,place_of_supply_text,reverse_charge_applies,
