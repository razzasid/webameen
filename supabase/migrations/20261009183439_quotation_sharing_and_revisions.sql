      'igst_total_minor',v_version.igst_total_minor::text,
      'gst_total_minor',v_version.gst_total_minor::text,'total_minor',v_version.total_minor::text),
    'lines',COALESCE((SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
      'position',i.position,'description',i.description,'unit_label',i.unit_label,
      'hsn_sac',i.hsn_sac,'quantity',i.quantity::text,
      'unit_price_minor',i.unit_price_minor::text,
      'line_subtotal_minor',i.line_subtotal_minor::text,
      'gst_category',i.gst_category,'gst_treatment',i.gst_treatment,
      'gst_rate',i.gst_rate::text,'taxable_amount_minor',i.taxable_amount_minor::text,
      'cgst_rate',i.cgst_rate::text,'cgst_amount_minor',i.cgst_amount_minor::text,
      'sgst_rate',i.sgst_rate::text,'sgst_amount_minor',i.sgst_amount_minor::text,
      'igst_rate',i.igst_rate::text,'igst_amount_minor',i.igst_amount_minor::text,
      'line_total_minor',i.line_total_minor::text)
      ORDER BY i.position) FROM public.quotation_items AS i
      WHERE i.business_id=v_business_id AND i.version_id=v_version_id),'[]'::jsonb),
    'response',CASE WHEN v_response.id IS NULL THEN NULL ELSE pg_catalog.jsonb_build_object(
      'kind',v_response.kind,'customer_note',v_response.customer_note,
      'respondent_name',v_response.respondent_name,'responded_at',v_response.responded_at) END
  );
END
