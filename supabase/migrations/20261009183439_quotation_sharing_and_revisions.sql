-- Share freezes the current complete draft and inserts its first bearer link
-- in one transaction. The token itself is generated by the server; only its
-- validated SHA-256 hex digest reaches this function.
CREATE FUNCTION private.share_quotation_draft(
  p_quotation_id uuid,
  p_version_id uuid,
  p_creation_request_key uuid,
  p_token_hash_hex text,
  p_access_expires_at timestamptz DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_user_id uuid := auth.uid();
  v_business_id uuid;
  v_quote public.quotations;
  v_version public.quotation_versions;
  v_existing public.quotation_public_links;
  v_now timestamptz;
  v_response_deadline timestamptz;
  v_line_count bigint;
BEGIN
  IF v_user_id IS NULL OR p_quotation_id IS NULL OR p_version_id IS NULL
    OR p_creation_request_key IS NULL OR p_token_hash_hex IS NULL
    OR p_token_hash_hex !~ '^[0-9a-fA-F]{64}$' THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Invalid quotation share request';
  END IF;
  -- Preserve the documented lock order: selectable GST options, business,
  -- then quotation. Recheck active membership after the business lock.
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/gst-options', 0));
  SELECT business_id INTO v_business_id FROM public.business_memberships
    WHERE user_id=v_user_id;
  IF v_business_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/business/'||v_business_id::text, 0));
  IF NOT EXISTS (SELECT 1 FROM public.business_memberships
    WHERE business_id=v_business_id AND user_id=v_user_id
      AND role='owner' AND disabled_at IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required';
  END IF;
  SELECT * INTO v_quote FROM public.quotations
    WHERE business_id=v_business_id AND id=p_quotation_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Quotation unavailable';
  END IF;

  -- Idempotency is resolved before checking whether this is still a draft.
  SELECT * INTO v_existing FROM public.quotation_public_links
    WHERE business_id=v_business_id AND creation_request_key=p_creation_request_key;
  IF FOUND THEN
    IF v_existing.quotation_id<>p_quotation_id
      OR v_existing.version_id<>p_version_id
      OR v_existing.access_expires_at IS DISTINCT FROM p_access_expires_at THEN
      RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Share request key was used for different inputs';
    END IF;
    RETURN pg_catalog.jsonb_build_object(
      'link_id',v_existing.id,'created',false,
      'active',v_existing.revoked_at IS NULL AND
        (v_existing.access_expires_at IS NULL OR v_existing.access_expires_at>pg_catalog.clock_timestamp()),
      'access_expires_at',v_existing.access_expires_at);
  END IF;

  SELECT * INTO v_version FROM public.quotation_versions
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id AND id=p_version_id;
  IF NOT FOUND OR v_quote.current_version_id<>p_version_id
    OR v_version.state<>'draft' OR v_version.shared_at IS NOT NULL THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Only the current draft can be shared';
  END IF;
  IF EXISTS (SELECT 1 FROM public.invoices
      WHERE business_id=v_business_id AND quotation_id=p_quotation_id) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='An invoiced quotation cannot be shared again';
  END IF;
  IF v_version.seller_display_name IS NULL OR pg_catalog.btrim(v_version.seller_display_name)=''
    OR v_version.seller_postal_address IS NULL OR pg_catalog.btrim(v_version.seller_postal_address)=''
    OR v_version.seller_country_code IS DISTINCT FROM 'IN'
    OR v_version.seller_state_code IS NULL
    OR v_version.seller_gst_registered IS NULL
    OR (v_version.seller_gst_registered AND
      (v_version.seller_gstin IS NULL OR v_version.seller_gstin !~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][A-Z0-9]{3}$'))
    OR v_version.buyer_display_name IS NULL OR pg_catalog.btrim(v_version.buyer_display_name)=''
    OR v_version.buyer_billing_address IS NULL OR pg_catalog.btrim(v_version.buyer_billing_address)=''
    OR v_version.buyer_state_code IS NULL
    OR v_version.buyer_gstin_applicable IS NULL
    OR (v_version.buyer_gstin_applicable AND
      (v_version.buyer_gstin IS NULL OR v_version.buyer_gstin !~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][A-Z0-9]{3}$'))
    OR v_version.currency_code IS DISTINCT FROM 'INR'
    OR v_version.currency_exponent IS DISTINCT FROM 2
    OR v_version.quantity_scale IS DISTINCT FROM 3
    OR v_version.calculation_rule_code IS DISTINCT FROM 'in-gst-exclusive-line-paise-half-up-v1'
    OR v_version.price_tax_mode IS DISTINCT FROM 'exclusive'
    OR v_version.document_time_zone IS NULL
    OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_timezone_names
        WHERE name=v_version.document_time_zone)
    OR v_version.place_of_supply_applicable IS NULL
    OR (v_version.place_of_supply_applicable AND v_version.place_of_supply_state_code IS NULL)
    OR (NOT v_version.place_of_supply_applicable AND
      (v_version.place_of_supply_state_code IS NOT NULL OR v_version.place_of_supply_text IS NOT NULL))
    OR v_version.reverse_charge_applies IS NULL
    OR v_version.gst_auto_treatment IS DISTINCT FROM
      (CASE WHEN v_version.seller_state_code=v_version.buyer_state_code THEN 'cgst_sgst' ELSE 'igst' END)
    OR v_version.gst_treatment IS DISTINCT FROM
      COALESCE(v_version.gst_treatment_override,v_version.gst_auto_treatment) THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Complete and review the quotation details before sharing';
  END IF;
  IF v_version.seller_contact_email IS NOT NULL AND
       v_version.seller_contact_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    OR v_version.buyer_email IS NOT NULL AND
       v_version.buyer_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Correct the email address before sharing';
  END IF;
  SELECT count(*) INTO v_line_count FROM public.quotation_items
    WHERE business_id=v_business_id AND version_id=p_version_id;
  IF v_line_count=0 THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Add at least one quotation line before sharing';
  END IF;
  IF EXISTS (SELECT 1 FROM public.quotation_items AS i
      WHERE i.business_id=v_business_id AND i.version_id=p_version_id
        AND i.gst_category='taxable'
        AND NOT EXISTS (SELECT 1 FROM public.gst_rate_options AS r
          WHERE r.rate=i.gst_rate AND r.selectable)) THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Select a currently configured GST rate before sharing';
  END IF;
  IF (v_version.seller_logo_asset_key IS NULL)<>(v_version.seller_logo_sha256 IS NULL)
    OR (v_version.seller_signature_asset_key IS NULL)<>(v_version.seller_signature_sha256 IS NULL)
    OR (v_version.seller_logo_sha256 IS NOT NULL AND pg_catalog.octet_length(v_version.seller_logo_sha256)<>32)
    OR (v_version.seller_signature_sha256 IS NOT NULL AND pg_catalog.octet_length(v_version.seller_signature_sha256)<>32) THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='A configured document image is unavailable';
  END IF;
  v_now := pg_catalog.clock_timestamp();
  IF v_version.valid_until IS NOT NULL THEN
    v_response_deadline := (v_version.valid_until + 1)::timestamp AT TIME ZONE v_version.document_time_zone;
    IF v_response_deadline<=v_now THEN
      RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='The quotation response deadline has passed';
    END IF;
  END IF;
  IF p_access_expires_at IS NOT NULL AND p_access_expires_at<=v_now THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='The link access cutoff must be in the future';
  END IF;

  UPDATE public.quotation_public_links SET
    revoked_by=v_user_id,revoked_at=v_now,revocation_reason='revision_shared'
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id AND revoked_at IS NULL;
  UPDATE public.quotation_versions SET
    state='shared',shared_by=v_user_id,shared_at=v_now,
    response_deadline_at=v_response_deadline
    WHERE business_id=v_business_id AND id=p_version_id;
  INSERT INTO public.quotation_public_links(
    business_id,quotation_id,version_id,token_hash,creation_request_key,
    access_expires_at,created_by,created_at)
  VALUES (v_business_id,p_quotation_id,p_version_id,
    pg_catalog.decode(p_token_hash_hex,'hex'),p_creation_request_key,
    p_access_expires_at,v_user_id,v_now)
  RETURNING * INTO v_existing;
  UPDATE public.quotations SET updated_at=v_now
    WHERE business_id=v_business_id AND id=p_quotation_id;
  RETURN pg_catalog.jsonb_build_object(
    'link_id',v_existing.id,'created',true,'active',true,
    'access_expires_at',v_existing.access_expires_at);
END
$fn$;

CREATE FUNCTION private.rotate_quotation_link(
  p_quotation_id uuid,
  p_version_id uuid,
  p_creation_request_key uuid,
  p_token_hash_hex text,
  p_access_expires_at timestamptz DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_user_id uuid := auth.uid();
  v_business_id uuid;
  v_quote public.quotations;
  v_version public.quotation_versions;
  v_existing public.quotation_public_links;
  v_now timestamptz;
BEGIN
  IF v_user_id IS NULL OR p_quotation_id IS NULL OR p_version_id IS NULL OR p_creation_request_key IS NULL
    OR p_token_hash_hex IS NULL OR p_token_hash_hex !~ '^[0-9a-fA-F]{64}$' THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Invalid quotation link request';
  END IF;
  SELECT business_id INTO v_business_id FROM public.business_memberships WHERE user_id=v_user_id;
  IF v_business_id IS NULL THEN RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required'; END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/business/'||v_business_id::text,0));
  IF NOT EXISTS (SELECT 1 FROM public.business_memberships
    WHERE business_id=v_business_id AND user_id=v_user_id AND role='owner' AND disabled_at IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Active owner required';
  END IF;
  SELECT * INTO v_quote FROM public.quotations
    WHERE business_id=v_business_id AND id=p_quotation_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Quotation unavailable'; END IF;
  SELECT * INTO v_existing FROM public.quotation_public_links
    WHERE business_id=v_business_id AND creation_request_key=p_creation_request_key;
  IF FOUND THEN
    IF v_existing.quotation_id<>p_quotation_id
      OR v_existing.version_id<>p_version_id
      OR v_existing.access_expires_at IS DISTINCT FROM p_access_expires_at THEN
