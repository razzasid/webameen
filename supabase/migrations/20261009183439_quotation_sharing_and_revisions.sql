    END IF;
    RETURN pg_catalog.jsonb_build_object(
      'link_id',v_existing.id,'created',false,
      'active',v_existing.revoked_at IS NULL AND
        (v_existing.access_expires_at IS NULL OR v_existing.access_expires_at>pg_catalog.clock_timestamp()),
      'access_expires_at',v_existing.access_expires_at);
  END IF;
  SELECT * INTO v_version FROM public.quotation_versions
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id
      AND id=p_version_id;
  IF NOT FOUND OR v_quote.current_version_id<>p_version_id
    OR v_version.shared_at IS NULL OR v_version.state='superseded'
    OR EXISTS (SELECT 1 FROM public.invoices
      WHERE business_id=v_business_id AND quotation_id=p_quotation_id) THEN
    RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Only the current frozen quotation can have its link rotated';
  END IF;
  v_now:=pg_catalog.clock_timestamp();
  IF p_access_expires_at IS NOT NULL AND p_access_expires_at<=v_now THEN
    RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='The link access cutoff must be in the future';
  END IF;
  UPDATE public.quotation_public_links SET
    revoked_by=v_user_id,revoked_at=v_now,revocation_reason='rotated'
    WHERE business_id=v_business_id AND quotation_id=p_quotation_id AND revoked_at IS NULL;
  INSERT INTO public.quotation_public_links(
    business_id,quotation_id,version_id,token_hash,creation_request_key,
    access_expires_at,created_by,created_at)
  VALUES (v_business_id,p_quotation_id,v_version.id,
    pg_catalog.decode(p_token_hash_hex,'hex'),p_creation_request_key,
    p_access_expires_at,v_user_id,v_now)
  RETURNING * INTO v_existing;
  UPDATE public.quotations SET updated_at=v_now
    WHERE business_id=v_business_id AND id=p_quotation_id;
  RETURN pg_catalog.jsonb_build_object(
    'link_id',v_existing.id,'created',true,'active',true,
    'access_expires_at',v_existing.access_expires_at);
END
