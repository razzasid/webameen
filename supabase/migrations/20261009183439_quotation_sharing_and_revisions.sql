-- supplies only a SHA-256 digest; quote/version IDs are resolved from it.
CREATE FUNCTION private.read_public_quotation(p_token_hash_hex text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE
  v_hash bytea; v_business_id uuid; v_quote_id uuid; v_version_id uuid;
  v_link record; v_quote record; v_version record; v_response record;
  v_now timestamptz;
BEGIN
  IF p_token_hash_hex IS NULL OR p_token_hash_hex !~ '^[0-9a-fA-F]{64}$' THEN RETURN NULL; END IF;
  v_hash:=pg_catalog.decode(p_token_hash_hex,'hex');
  SELECT l.business_id,l.quotation_id,l.version_id
    INTO v_business_id,v_quote_id,v_version_id
    FROM public.quotation_public_links AS l WHERE l.token_hash=v_hash;
  IF NOT FOUND THEN RETURN NULL; END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock_shared(
    pg_catalog.hashtextextended('webameen/business/'||v_business_id::text,0));
  IF NOT EXISTS (SELECT 1 FROM public.business_memberships AS m
    WHERE m.business_id=v_business_id AND m.disabled_at IS NULL) THEN RETURN NULL; END IF;
  SELECT q.id,q.business_id,q.reference,q.current_version_id INTO v_quote FROM public.quotations AS q
    WHERE q.business_id=v_business_id AND q.id=v_quote_id FOR UPDATE;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT l.id,l.business_id,l.quotation_id,l.version_id,l.token_hash,
      l.access_expires_at,l.created_at,l.revoked_at INTO v_link
    FROM public.quotation_public_links AS l
    WHERE l.business_id=v_business_id AND l.quotation_id=v_quote_id
      AND l.version_id=v_version_id AND l.token_hash=v_hash;
  IF NOT FOUND OR v_link.revoked_at IS NOT NULL THEN RETURN NULL; END IF;
  v_now:=pg_catalog.clock_timestamp();
  IF v_link.access_expires_at IS NOT NULL AND v_now>=v_link.access_expires_at THEN RETURN NULL; END IF;
  SELECT v.id,v.business_id,v.quotation_id,v.version_number,v.previous_version_id,v.state,
      v.valid_until,v.response_deadline_at,v.shared_by,v.shared_at,
      v.seller_display_name,v.seller_contact_email,v.seller_contact_phone,
      v.seller_postal_address,v.seller_country_code,v.seller_state_code,
      v.seller_gst_registered,v.seller_gstin,v.buyer_display_name,v.buyer_contact_name,
      v.buyer_email,v.buyer_phone,v.buyer_billing_address,v.buyer_state_code,
      v.buyer_gstin_applicable,v.buyer_gstin,v.currency_code,v.currency_exponent,
      v.quantity_scale,v.calculation_rule_code,v.price_tax_mode,v.gst_auto_treatment,
      v.gst_treatment_override,v.gst_treatment,v.document_time_zone,
      v.place_of_supply_applicable,v.place_of_supply_state_code,v.place_of_supply_text,
      v.reverse_charge_applies,v.subtotal_minor,v.taxable_subtotal_minor,
      v.cgst_total_minor,v.sgst_total_minor,v.igst_total_minor,v.gst_total_minor,
      v.total_minor,v.seller_bank_name,v.seller_bank_account_name,
      v.seller_bank_account_number,v.seller_bank_ifsc,v.seller_upi_id,
      v.payment_instructions,v.terms INTO v_version
    FROM public.quotation_versions AS v
    WHERE v.business_id=v_business_id AND v.quotation_id=v_quote_id
      AND v.id=v_version_id AND v.shared_at IS NOT NULL;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT r.id,r.public_link_id,r.kind,r.customer_note,r.respondent_name,r.responded_at
    INTO v_response FROM public.quotation_responses AS r
    WHERE r.business_id=v_business_id AND r.quotation_id=v_quote_id AND r.version_id=v_version_id;
  RETURN pg_catalog.jsonb_build_object(
    'reference',v_quote.reference,'version_number',v_version.version_number,
    'state',v_version.state,'revision_in_preparation',v_quote.current_version_id<>v_version.id,
    'valid_until',v_version.valid_until,'response_deadline_at',v_version.response_deadline_at,
    'response_deadline_passed',v_version.response_deadline_at IS NOT NULL AND v_now>=v_version.response_deadline_at,
    'seller',pg_catalog.jsonb_build_object(
      'display_name',v_version.seller_display_name,'email',v_version.seller_contact_email,
      'phone',v_version.seller_contact_phone,'address',v_version.seller_postal_address,
      'country_code',v_version.seller_country_code,'state_code',v_version.seller_state_code,
      'gst_registered',v_version.seller_gst_registered,'gstin',v_version.seller_gstin,
      'bank_name',v_version.seller_bank_name,'bank_account_name',v_version.seller_bank_account_name,
      'bank_account_number',v_version.seller_bank_account_number,'bank_ifsc',v_version.seller_bank_ifsc,
      'upi_id',v_version.seller_upi_id,'payment_instructions',v_version.payment_instructions),
    'buyer',pg_catalog.jsonb_build_object(
      'display_name',v_version.buyer_display_name,'contact_name',v_version.buyer_contact_name,
      'email',v_version.buyer_email,'phone',v_version.buyer_phone,
      'billing_address',v_version.buyer_billing_address,'state_code',v_version.buyer_state_code,
      'gstin_applicable',v_version.buyer_gstin_applicable,'gstin',v_version.buyer_gstin),
    'document',pg_catalog.jsonb_build_object(
      'currency_code',v_version.currency_code,'currency_exponent',v_version.currency_exponent,
      'quantity_scale',v_version.quantity_scale,'calculation_rule_code',v_version.calculation_rule_code,
      'price_tax_mode',v_version.price_tax_mode,'gst_auto_treatment',v_version.gst_auto_treatment,
      'gst_treatment_override',v_version.gst_treatment_override,'gst_treatment',v_version.gst_treatment,
      'document_time_zone',v_version.document_time_zone,
      'place_of_supply_applicable',v_version.place_of_supply_applicable,
      'place_of_supply_state_code',v_version.place_of_supply_state_code,
      'place_of_supply_text',v_version.place_of_supply_text,
